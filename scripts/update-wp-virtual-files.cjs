const fs = require('fs');
const path = require('path');

function getLanguage(filePath) {
    const ext = path.extname(filePath).slice(1);
    if (ext === 'php') return 'php';
    if (ext === 'css') return 'css';
    if (ext === 'js') return 'js';
    if (ext === 'json') return 'json';
    if (ext === 'svg') return 'svg';
    if (ext === 'md') return 'markdown';
    return 'txt';
}

function getPackage(filePath) {
    if (filePath.includes('hackersshikkhok-core')) return 'core';
    if (filePath.includes('hackersshikkhok-theme')) return 'theme';
    return 'docs';
}

function escapeContent(content) {
    return content
        .replace(/\\/g, '\\\\')
        .replace(/"/g, '\\"')
        .replace(/\n/g, '\\n')
        .replace(/\r/g, '\\r');
}

const BINARY_EXTENSIONS = new Set([
    '.png', '.jpg', '.jpeg', '.webp', '.gif', '.ico',
    '.woff', '.woff2', '.ttf', '.eot', '.zip', '.pdf'
]);

function walkDir(dir, fileList = []) {
    const files = fs.readdirSync(dir, { withFileTypes: true });
    for (const file of files) {
        const fullPath = path.join(dir, file.name);
        if (file.isDirectory()) {
            if (file.name === 'node_modules' || file.name === '.git' || file.name === 'dist') continue;
            walkDir(fullPath, fileList);
        } else {
            const ext = path.extname(file.name).toLowerCase();
            if (BINARY_EXTENSIONS.has(ext)) continue;
            fileList.push(fullPath);
        }
    }
    return fileList;
}

