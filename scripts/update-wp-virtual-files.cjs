export async function generateAndDownloadZip(
  files: VirtualFile[],
  pkg: 'theme' | 'core' | 'docs' | 'all'
): Promise<{ fileName: string; fileCount: number; sizeBytes: number }> {
  const zip = new JSZip();
  const filterPkg = pkg === 'all' ? null : pkg;

  const targetFiles = filterPkg ? files.filter(f => f.package === filterPkg) : files;

  targetFiles.forEach((file) => {
    zip.file(file.path, file.content);
  });

  const blob = await zip.generateAsync({ type: 'blob' });
  const fileName = pkg === 'core' 
    ? 'hackersshikkhok-core.zip' 
    : (pkg === 'theme' ? 'hackersshikkhok-theme.zip' : (pkg === 'docs' ? 'hackersshikkhok-docs.zip' : 'hackersshikkhok-complete.zip'));

  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);

  return {
    fileName,
    fileCount: targetFiles.length,
    sizeBytes: blob.size,
  };
}

